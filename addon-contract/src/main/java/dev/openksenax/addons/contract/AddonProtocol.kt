package dev.openksenax.addons.contract

/**
 * Содержит текущие версии публичных контрактов между OpenKsenax
 * и подключаемыми addon APK.
 *
 * Версия протокола описывает формат и правила обмена данными между host
 * и аддоном. Версия host API описывает набор возможностей, которые host
 * предоставляет аддону во время обнаружения, управления и исполнения.
 *
 * Эти версии развиваются независимо: формат обмена может измениться
 * без добавления новых возможностей, а host API может расшириться
 * без изменения формата протокола.
 *
 * @since 0.3
 * @author Stephan Kolesnikov
 */
object AddonProtocol {

    /**
     * Текущая версия формата и правил взаимодействия между OpenKsenax
     * и addon APK.
     *
     * Используется при проверке совместимости manifest и management-
     * взаимодействия аддона с host-приложением.
     *
     * @since 0.3
     */
    const val CURRENT_PROTOCOL_VERSION: Int = 1

    /**
     * Текущая версия набора возможностей, предоставляемых OpenKsenax
     * подключаемым аддонам.
     *
     * Используется для проверки того, поддерживает ли host возможности,
     * необходимые конкретному аддону.
     *
     * @since 0.3
     */
    const val CURRENT_HOST_API: Int = 1
}