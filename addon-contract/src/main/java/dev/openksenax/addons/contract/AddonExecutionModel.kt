package dev.openksenax.addons.contract

/**
 * Определяет архитектурную модель исполнения аддона относительно
 * host-приложения OpenKsenax.
 *
 * Модель исполнения задаёт, где физически работает код аддона, кто владеет
 * его Android lifecycle, процессом, фоновым runtime и пользовательским
 * интерфейсом. Значение публикуется в `AndroidManifest.xml` аддона и используется
 * OpenKsenax при discovery и проверке совместимости.
 *
 * Имена опубликованных значений могут использоваться как часть manifest-протокола
 * и поэтому не должны переименовываться без механизма миграции.
 *
 * @since 0.3
 * @author Stephan Kolesnikov
 */
enum class AddonExecutionModel {

    /**
     * Исполняет аддон как самостоятельное Android-приложение.
     *
     * Аддон работает под собственным UID и, как правило, в отдельном процессе,
     * владеет своим UI, сервисами, данными, permissions и жизненным циклом.
     * Он самостоятельно поддерживает необходимый background runtime, а с
     * OpenKsenax взаимодействует через публичные IPC- и capability-контракты.
     *
     * Ошибка или остановка процесса аддона не должна напрямую останавливать
     * процесс OpenKsenax. Host управляет аддоном только через опубликованный
     * management API и не владеет его внутренними Android-компонентами.
     *
     * @since 0.3
     */
    AUTONOMOUS_APPLICATION,
}